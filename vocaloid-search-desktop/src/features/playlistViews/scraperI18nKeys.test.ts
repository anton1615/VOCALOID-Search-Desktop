    expect(source).toContain("t('scraper.importExecuting')")
    expect(source).toContain("t('scraper.importPreviewError')")
    expect(source).toContain("t('scraper.importExecuteError')")
    expect(source).toContain("t('scraper.searchKeywordPlaceholder')")
